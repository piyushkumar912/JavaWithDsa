//Relational Operators --> (== , != , > , < , >=, <=)

import java.util.*;
public class Arithematic2 {
    public static void main (String args[]){
        int a = 70;
        int b = 70;
        System.out.println(a == b);
        System.out.println(a != b);
        System.out.println(a > b);
        System.out.println(a < b);
        System.out.println(a >= b);
        System.out.println(a <= b);
    }
}
