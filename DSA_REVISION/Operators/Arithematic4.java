//Assignemnt Operators --> (= , += , -= , *=, /= , %=)

import java.util.*;
public class Arithematic4 {
    public static void main(String args[]){
        int a = 10;
        // a = a +10;
        a += 10;
        int b = 50;
        // b = b - 25;
        b -= 25;
        int c = 20;
        // c = c * 2;
        c *= 2;
        int d = 40;
        // d = d / 2;
        d /= 2;
        int e = 55;
        // e = e % 2;
        e %= 2;
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);
    }
}
