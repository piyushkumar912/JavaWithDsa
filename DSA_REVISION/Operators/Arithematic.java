//Binary Operators -->>(+ , - , * , / , %).

import java.util.*;
public class Arithematic {
    public static void main(String args[]){
        int A = 10;
        int B = 5;
        System.out.println(A + B);
        System.out.println(A - B);
        System.out.println(A * B);
        System.out.println(A / B);
        System.out.println(A % B);
    }
}
